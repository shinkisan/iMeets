    /// True only when the whole line is a curated key (no part or fuzzy
    /// matching). Used to decide whether a dynamic price may stay in the line.
    static func hasExact(_ raw: String) -> Bool {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return false }
        if table[text] != nil { return true }
        let compact = text.replacingOccurrences(of: " ", with: "")
        return compact != text && table[compact] != nil
    }

    /// Exact match first, then a few normalisations for leading control
    /// glyphs and split buffers. Longest contained key is the last resort.
    static func lookup(_ raw: String, strict: Bool = false) -> String? {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return nil }
        // The name-entry prompt is fixed even when the typed name follows it.
        if text.hasPrefix("あなたのなまえは") { return "你叫什么名字？" }
        var variants: [String] = [text]
        let spaced = text.replacingOccurrences(of: "□", with: " ")
            .split(separator: " ", omittingEmptySubsequences: true).joined(separator: " ")
        if spaced != text { variants.append(spaced) }
        let stripped = text.replacingOccurrences(of: "□", with: "")
        if stripped != text { variants.append(stripped) }
        let compact = text.replacingOccurrences(of: " ", with: "")
        if compact != text { variants.append(compact) }
        if !strict {
            if text.hasPrefix("み") { variants.append(String(text.dropFirst())) }
            if text.count > 1 { variants.append(String(text.dropFirst())) }
            if text.count > 2 { variants.append(String(text.dropFirst(2))) }
        }
        for variant in variants {
            if let hit = table[variant] { return hit }
        }
        let parts = text.split(separator: " ", omittingEmptySubsequences: true)
        if parts.count > 1 {
            let translated = parts.compactMap { part -> String? in
                let value = String(part)
                if let known = table[value] { return known }
                for (suffix, format) in [("代目", "第%@代"), ("才", "%@岁"), ("G", "%@ G"), ("月", "%@月"), ("日", "%@日")] {
                    guard value.hasSuffix(suffix) else { continue }
                    let number = String(value.dropLast(suffix.count))
                    if !number.isEmpty && number.unicodeScalars.allSatisfy({ (48...57).contains($0.value) }) {
                        return String(format: format, number as NSString)
                    }
                }
                return nil
            }
            if translated.count == parts.count { return translated.joined(separator: " / ") }
            return nil
        }
        if strict { return nil }
        var best: (Int, String)?
        for (key, value) in table where key.count >= 2 && text.contains(key) {
            if best == nil || key.count > best!.0 { best = (key.count, value) }
        }
        return best?.1
    }
